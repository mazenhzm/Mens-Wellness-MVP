def _database_settings():
    raw_url = os.environ.get("DATABASE_URL", "").strip()
    if not raw_url:
        raise ImproperlyConfigured("DATABASE_URL must be provided by the Replit PostgreSQL database.")

    parsed = urlparse(raw_url)
    if parsed.scheme not in {"postgres", "postgresql"} or not parsed.path.strip("/"):
        raise ImproperlyConfigured("DATABASE_URL must be a valid PostgreSQL connection URL.")

    database = {
        "ENGINE": "django.db.backends.postgresql",
        "NAME": unquote(parsed.path.lstrip("/")),
        "USER": unquote(parsed.username or ""),
        "PASSWORD": unquote(parsed.password or ""),
        "HOST": parsed.hostname or "",
        "PORT": str(parsed.port or ""),
        "CONN_MAX_AGE": int(os.environ.get("DB_CONN_MAX_AGE", "60")),
        "CONN_HEALTH_CHECKS": True,
        "OPTIONS": {"connect_timeout": 5},
    }
    sslmode = parse_qs(parsed.query).get("sslmode", [None])[0]
    if sslmode:
        database["OPTIONS"]["sslmode"] = sslmode
    return {"default": database}


DATABASES = _database_settings()


